const encoder = new TextEncoder();
const decoder = new TextDecoder();

/**
 * Safely converts a Uint8Array to a Base64 string without stack overflow.
 */
function uint8ArrayToBase64(bytes: Uint8Array): string {
  let binary = "";
  const len = bytes.byteLength;
  const chunkSize = 0x8000; // Process in 32KB chunks to prevent stack overflow
  for (let i = 0; i < len; i += chunkSize) {
    const chunk = bytes.subarray(i, i + chunkSize);
    binary += String.fromCharCode(...chunk);
  }
  return btoa(binary);
}

/**
 * Derives a secure 256-bit AES key from a password using PBKDF2
 */
async function deriveKey(
  password: string,
  salt: Uint8Array,
): Promise<CryptoKey> {
  const passwordBuffer = encoder.encode(password);

  const baseKey = await globalThis.crypto.subtle.importKey(
    "raw",
    passwordBuffer,
    "PBKDF2",
    false,
    ["deriveKey"],
  );

  return globalThis.crypto.subtle.deriveKey(
    {
      name: "PBKDF2",
      salt: salt as unknown as BufferSource, // <-- Fixes the type mismatch error
      iterations: 600000,
      hash: "SHA-256",
    },
    baseKey,
    { name: "AES-GCM", length: 256 },
    false,
    ["encrypt", "decrypt"],
  );
}

/**
 * Encrypts plain text using a password (AES-GCM 256)
 * @returns A single Base64 encoded string containing Salt + IV + Ciphertext
 */
export async function encryptText(
  plainText: string,
  password: string,
): Promise<string> {
  const salt = globalThis.crypto.getRandomValues(new Uint8Array(16)); // 16 bytes salt
  const iv = globalThis.crypto.getRandomValues(new Uint8Array(12)); // 12 bytes IV for GCM

  const aesKey = await deriveKey(password, salt);
  const encryptedBuffer = await globalThis.crypto.subtle.encrypt(
    { name: "AES-GCM", iv },
    aesKey,
    encoder.encode(plainText),
  );

  // Combine Salt (16B) + IV (12B) + Ciphertext into one array
  const combined = new Uint8Array(
    salt.length + iv.length + encryptedBuffer.byteLength,
  );
  combined.set(salt, 0);
  combined.set(iv, salt.length);
  combined.set(new Uint8Array(encryptedBuffer), salt.length + iv.length);

  // Convert binary data safely to standard Base64 string
  return uint8ArrayToBase64(combined);
}

/**
 * Decrypts a packed Base64 string back into plain text
 * @param base64String The Salt + IV + Ciphertext string generated by encryptText
 */
export async function decryptText(
  base64String: string,
  password: string,
): Promise<string> {
  try {
    const binaryString = atob(base64String);
    const combined = Uint8Array.from(binaryString, (char) =>
      char.charCodeAt(0),
    );

    // Ensure the payload is at least as long as Salt (16) + IV (12) = 28 bytes
    if (combined.length < 28) {
      throw new Error("Invalid encrypted payload structure.");
    }

    // Extract the exact lengths we packed during encryption
    const salt = combined.slice(0, 16);
    const iv = combined.slice(16, 28);
    const ciphertext = combined.slice(28);

    const aesKey = await deriveKey(password, salt);
    const decryptedBuffer = await globalThis.crypto.subtle.decrypt(
      { name: "AES-GCM", iv },
      aesKey,
      ciphertext,
    );

    return decoder.decode(decryptedBuffer);
  } catch {
    throw new Error("Decryption failed. Invalid password or corrupted text.");
  }
}
